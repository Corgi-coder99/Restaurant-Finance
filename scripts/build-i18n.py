"""Compile the reviewed source-string translation catalogue. No network dependency."""
import json
from pathlib import Path
root=Path(__file__).resolve().parent.parent
catalog={}
for number,line in enumerate((root/'scripts/translations.tsv').read_text().splitlines(),1):
    if not line.strip():continue
    parts=line.split('|')
    if len(parts)!=4:raise ValueError(f'Translation row {number}: expected 4 columns')
    source,*translations=parts
    entry=dict(zip(['en','fr','de'],translations))
    if source in catalog and catalog[source]!=entry:raise ValueError(f'Conflicting translation: {source}')
    catalog[source]=entry
(root/'dist/i18n-catalog.js').write_text('/* Generated by scripts/build-i18n.py */\nglobalThis.BepTranslations = '+json.dumps(catalog,ensure_ascii=False,separators=(',',':'))+';\n')
print('Built',len(catalog),'UI messages in 4 languages')
